/// Everything needed to recompute the expectations.
#[derive(Debug, Deserialize)]
#[serde(deny_unknown_fields)]
struct Inputs {
    /// The documented fixed test seed (hex).
    w: String,
    /// The `s_root` derivation label (see [`S_ROOT_LABEL`]).
    s_root_label: String,
    /// The cases, each a content vector plus the openings to prove.
    cases: Vec<CaseInput>,
}

#[derive(Debug, Deserialize)]
#[serde(deny_unknown_fields)]
struct CaseInput {
    name: String,
    /// The file's byte-domain content, hex; its length **is** `n`.
    content: String,
    openings: Vec<OpeningInput>,
}

#[derive(Debug, Deserialize)]
#[serde(deny_unknown_fields)]
struct OpeningInput {
    name: String,
    start: u64,
    length: u64,
}

