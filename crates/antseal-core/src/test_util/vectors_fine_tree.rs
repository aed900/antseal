/// Every grid node covering at least one real leaf, in `(level, index)` order.
fn used_grid_nodes(leaf_count: u64, depth: u8) -> Vec<(u8, u64)> {
    let mut nodes = Vec::new();
    for level in 0..=depth {
        for index in 0..(1u64 << level) {
            if (index << (depth - level)) < leaf_count {
                nodes.push((level, index));
            }
        }
    }
    nodes
}

/// `NodeAddress::try_new`, reported as a vector error rather than unwrapped.
fn address_of(level: u8, index: u64) -> Result<NodeAddress, VectorError> {
    NodeAddress::try_new(level, index)
        .map_err(|e| check_err("node-address", format!("({level},{index}): {e}")))
}

/// The index whose MSB-first path is the reverse of `index`'s. Equal to
/// `index` exactly when the path is palindromic, which is when the two bit
/// orders cannot be told apart.
fn reversed_path_index(index: u64, depth: u8) -> u64 {
    let mut reversed = 0u64;
    for bit in 0..depth {
        reversed |= ((index >> bit) & 1) << (depth - 1 - bit);
    }
    reversed
}

/// `salt_index` as an LSB-first implementation would compute it — the wrong
/// answer, derived on purpose so the executor can require that it *differs*.
fn lsb_first_salt(s_root: &Seed32, index: u64, depth: u8) -> Salt16 {
    let mut seed = Seed32::from_bytes(*s_root.as_bytes());
    for bit in 0..depth {
        seed = child_seed(
            &seed,
            crate::content::ChildBit::from_bit((index >> bit) & 1 == 1),
        );
    }
    let mut salt = [0u8; Salt16::LEN];
    salt.copy_from_slice(&seed.as_bytes()[..Salt16::LEN]);
    Salt16::from_bytes(salt)
}

/// All content-tree node spans under RFC 6962 promotion, pre-order.
fn collect_content_nodes(first: u64, end: u64, out: &mut Vec<(u64, u64)>) {
    out.push((first, end));
    if end.saturating_sub(first) <= 1 {
        return;
    }
    let split = rfc6962_split(end - first);
    collect_content_nodes(first, first + split, out);
    collect_content_nodes(first + split, end, out);
}

/// The RFC 6962 hash of the subtree over leaves `[first, end)`.
///
/// Uses the crate's single leaf/node preimage sites and its single split
/// definition, so this reference cannot drift from the streaming builder;
/// independence from antseal-core altogether is the Python generator's job.
fn subtree_hash(tree: &SaltTree<'_>, content: &[u8], first: u64, end: u64) -> [u8; 32] {
    if end.saturating_sub(first) <= 1 {
        let salt = tree
            .salt(first)
            .unwrap_or_else(|| Salt16::from_bytes([0; 16]));
        let byte = usize::try_from(first)
            .ok()
            .and_then(|i| content.get(i))
            .copied()
            .unwrap_or(0);
        return leaf_hash(&salt, first, byte);
    }
    let split = rfc6962_split(end - first);
    node_hash(
        &subtree_hash(tree, content, first, first + split),
        &subtree_hash(tree, content, first + split, end),
    )
}

/// Locate the first structural difference between two JSON values, as a
/// path plus the two sides — so a failing vector says *where*, not just
/// "documents differ" over 18 kB of hex.
pub fn first_difference(
    path: &str,
    recomputed: &serde_json::Value,
    committed: &serde_json::Value,
) -> String {
    match (recomputed, committed) {
        (serde_json::Value::Object(a), serde_json::Value::Object(b)) => {
            for (key, value) in a {
                match b.get(key) {
                    None => return format!("{path}.{key}: recomputed has it, the file does not"),
                    Some(other) if other != value => {
                        return first_difference(&format!("{path}.{key}"), value, other);
                    }
                    Some(_) => {}
                }
            }
            for key in b.keys() {
                if !a.contains_key(key) {
                    return format!("{path}.{key}: the file has it, recomputation does not");
                }
            }
            format!("{path}: objects differ but no field does (unreachable)")
        }
        (serde_json::Value::Array(a), serde_json::Value::Array(b)) => {
            if a.len() != b.len() {
                return format!(
                    "{path}: recomputed {} entr(ies), the file pins {}",
                    a.len(),
                    b.len()
                );
            }
            for (i, (value, other)) in a.iter().zip(b).enumerate() {
                if value != other {
                    return first_difference(&format!("{path}[{i}]"), value, other);
                }
            }
            format!("{path}: arrays differ but no element does (unreachable)")
        }
        (a, b) => format!("{path}: recomputed {a}, the file pins {b}"),
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    /// The synthetic seed really is the documented derivation, and really is
    /// not the fixture `W` itself.
    #[test]
    fn s_root_is_the_documented_alternate_test_secret() {
        let s_root = alternate_test_secret(S_ROOT_LABEL.as_bytes());
        assert_ne!(s_root, TEST_MASTER_SECRET_W);
        let mut expected = Sha256::new();
        expected.update(S_ROOT_LABEL.as_bytes());
        expected.update(TEST_MASTER_SECRET_W);
        assert_eq!(s_root, <[u8; 32]>::from(expected.finalize()));
    }

    /// The MSB-first pin's own precondition. A path is *palindromic* when
    /// reading its bits the other way names the same leaf — at `d = 3` those
    /// are 0 (`000`), 2 (`010`), 5 (`101`) and 7 (`111`). Only the others —
    /// 1↔4 and 3↔6 — can tell the two bit orders apart, which is why the
    /// executor's divergence assertion skips the palindromic ones instead of
    /// asserting something false about them.
    #[test]
    fn reversed_path_index_identifies_the_palindromic_leaves() {
        for palindrome in [0u64, 2, 5, 7] {
            assert_eq!(
                reversed_path_index(palindrome, 3),
                palindrome,
                "{palindrome:03b} is its own reverse"
            );
        }
        assert_eq!(reversed_path_index(1, 3), 4);
        assert_eq!(reversed_path_index(4, 3), 1);
        assert_eq!(reversed_path_index(3, 3), 6);
        assert_eq!(reversed_path_index(6, 3), 3);
        assert_eq!(reversed_path_index(0, 0), 0);
    }

    /// The deliberately-wrong LSB-first walk diverges from the shipped
    /// derivation on **exactly** the non-palindromic indices — the executor's
    /// assertion is therefore neither vacuous (it does fire) nor false (it
    /// would not fire on 2 or 5).
    #[test]
    fn lsb_first_salt_diverges_exactly_on_non_palindromic_paths() {
        let s_root = Seed32::from_bytes(alternate_test_secret(S_ROOT_LABEL.as_bytes()));
        let tree = SaltTree::new(&s_root, 6).expect("n = 6");
        for index in 0..6u64 {
            let same = lsb_first_salt(&s_root, index, 3).as_bytes()
                == tree.salt(index).expect("in range").as_bytes();
            assert_eq!(
                same,
                reversed_path_index(index, 3) == index,
                "leaf {index:03b}: the two bit orders agree iff the path is palindromic"
            );
        }
    }

    /// The diff locator names the field, not just "they differ".
    #[test]
    fn first_difference_locates_the_field() {
        let a = serde_json::json!({"cases": [{"n": 6, "fine_root": "aa"}]});
        let b = serde_json::json!({"cases": [{"n": 6, "fine_root": "bb"}]});
        let message = first_difference("expect", &a, &b);
        assert!(message.contains("cases[0].fine_root"), "{message}");
        let short = serde_json::json!({"cases": []});
        assert!(first_difference("expect", &short, &b).contains("entr"));
    }
}
