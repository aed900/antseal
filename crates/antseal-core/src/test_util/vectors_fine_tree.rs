//! Golden-vector kind **`fine-tree`** (task G15): the fine-tree/GGM vectors,
//! whose reason for existing is to pin **MSB-first GGM leaf indexing**.
//!
//! Spec basis: the GGM fine tree and its normative cover rule (MVP-SPEC.md
//! line 96), the Merkle definitions with `0x00`/`0x01` domain separation and
//! RFC 6962 unbalanced promotion (line 78), the M0 milestone (line 153), and
//! Verification's **unbalanced-n golden vector** (line 169).
//!
//! # Why a vector kind rather than a `testdata/fine-tree/` tree
//!
//! tasks/G.md G15 sketches `testdata/fine-tree/`. Q2's layout decision makes
//! `testdata/vectors/<format-version>/` the home of *all* committed vectors,
//! Q6's freeze registry already carries the must-exist obligation under the
//! slug `fine-tree-unbalanced-n6`, and `testdata/vectors/README.md` reserved
//! the kind name `fine-tree` for exactly this task. Landing here therefore
//! clears that obligation and inherits, for free: the discovery contract, the
//! NON-SECRET enforcement, the misfiled-version check, the three-OS
//! `cross-os-*` lanes, Q6's per-version freeze, and the WASM-safe execution
//! path the Q5 native↔WASM bit-match lane reuses — exactly as C15's
//! `sig-reject` and C16's four kinds did. `testdata/fine-tree/README.md`
//! already anticipated this ("… may additionally land as `fine-tree` kind
//! vector files under `../vectors/<format-version>/`").
//!
//! # What the document pins
//!
//! For each case (`n = 6` unbalanced, `n = 1` root-is-leaf, `n = 0` no tree,
//! `n = 5` one past a power of two):
//!
//! - **every used GGM node seed** — the complete set of grid nodes covering
//!   at least one real leaf, so an indexing change is visible at every level
//!   and not only at the root;
//! - **every `salt_i`** — this is the MSB-first pin: reversing the bit order
//!   changes `salt_i` for every index whose bit pattern is not a palindrome;
//! - **every RFC 6962 content-tree node** under unbalanced promotion, each
//!   with the canonical grid slot its wire address would use, ordered by
//!   subtree width then first leaf (i.e. level by level from the leaves up);
//! - **`fine_root`**;
//! - and per opening the **full range proof**: the leaf-exact cover with its
//!   seeds, and the boundary Merkle path with its hashes.
//!
//! # How it is checked
//!
//! [`build_expect`] recomputes the *entire* `expect` object from `inputs`
//! through antseal-core's public API and the document is compared as a whole,
//! so a missing, extra, or reordered entry fails as loudly as a wrong byte.
//! On top of that, [`execute`] runs the assertions a value comparison cannot
//! express:
//!
//! 1. **MSB-first divergence** — the LSB-first walk is performed explicitly
//!    and must produce a *different* salt for every index whose reversed path
//!    differs. Without this, a document generated by an LSB-first
//!    implementation would be self-consistent.
//! 2. **Unused slots are never derived** — every grid node lying wholly at or
//!    past `n` must be refused by [`SaltTree::seed_at`], and the pinned node
//!    set must be exactly its complement.
//! 3. **Every opening verifies** — each proof is run back through
//!    [`verify_range`] (G13), so the vectors are openings that actually open.
//! 4. **`n = 0` has no tree at all** — asserted against the four entry points
//!    that must decline it.
//!
//! The `expect` values themselves are cross-checked against an **independent
//! implementation**: `testdata/vectors/v1/fine-tree/gen_vectors.py` rebuilds
//! the identical document from MVP-SPEC.md using the Python standard library
//! only, sharing no code with this crate.

