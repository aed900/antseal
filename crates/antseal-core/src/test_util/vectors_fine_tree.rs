/// The registered kind name.
pub const KIND: &str = "fine-tree";

/// The documented label of the synthetic file seed:
/// `s_root = SHA-256(S_ROOT_LABEL ‖ TEST_MASTER_SECRET_W)`.
///
/// The G15 task calls for "a fixed synthetic `s_root`". Inventing a fresh
/// 32-byte literal would breach the secret-material convention's "every
/// fixture secret is the documented seed or deterministically derived from
/// it" (`testdata/README.md`), so the seed is minted through the project's
/// [`alternate_test_secret`] construction instead: fixed, synthetic, clearly
/// labelled, and reproducible by any implementation reading this formula.
///
/// The label is a domain separator, not a secret: it appears verbatim in the
/// committed vector's `inputs.s_root_label`.
pub const S_ROOT_LABEL: &str = "antseal G15 fine-tree s_root";

/// Beyond this slot count the executor stops sweeping *every* grid node for
/// the unused-slot assertion. The committed cases all sit at `d <= 3`; the
/// bound exists so a future large-`n` case cannot turn the sweep quadratic.
const EXHAUSTIVE_SWEEP_SLOT_LIMIT: u64 = 1 << 12;

fn payload_err(problem: String) -> VectorError {
    VectorError::Payload {
        kind: KIND,
        problem,
    }
}

fn check_err(check: &'static str, problem: String) -> VectorError {
    VectorError::Check {
        kind: KIND,
        check,
        problem,
    }
}

