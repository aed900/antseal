/// The four properties a recomputed-and-compared document cannot state
/// (module docs §"How it is checked").
fn check_case_behaviour(
    s_root: &Seed32,
    case: &CaseInput,
    content: &[u8],
) -> Result<(), VectorError> {
    let n = u64::try_from(content.len()).unwrap_or(u64::MAX);
    let Some(depth) = depth_for_leaf_count(n) else {
        // 4. n = 0 has no tree at all, at every entry point that could offer
        //    one.
        if SaltTree::new(s_root, 0).is_some() {
            return Err(check_err(
                "empty-file-has-no-tree",
                "SaltTree::new accepted n = 0".to_owned(),
            ));
        }
        if rebuild_fine_root(s_root, &[]).is_some() {
            return Err(check_err(
                "empty-file-has-no-tree",
                "rebuild_fine_root produced a root for an empty file".to_owned(),
            ));
        }
        if minimal_cover(ByteRange::new(0, 1), 0).is_ok() {
            return Err(check_err(
                "empty-file-has-no-tree",
                "minimal_cover accepted a range against n = 0".to_owned(),
            ));
        }
        return Ok(());
    };
    let tree = SaltTree::new(s_root, n).ok_or_else(|| {
        check_err(
            "salt-tree",
            format!("case `{}`: no salt tree for n = {n}", case.name),
        )
    })?;

    // 1. MSB-first: walking the same index LSB-first must give a DIFFERENT
    //    salt wherever the reversed path differs. A document generated by an
    //    LSB-first implementation would be internally consistent, so this is
    //    the assertion that actually pins the bit order.
    for index in 0..n {
        if reversed_path_index(index, depth) == index {
            continue; // palindromic path: both orders agree by definition
        }
        let msb_first = tree.salt(index).ok_or_else(|| {
            check_err(
                "salt",
                format!("case `{}`: no salt for leaf {index}", case.name),
            )
        })?;
        if lsb_first_salt(s_root, index, depth).as_bytes() == msb_first.as_bytes() {
            return Err(check_err(
                "msb-first-indexing",
                format!(
                    "case `{}`: leaf {index}'s salt is identical under LSB-first \
                     derivation — the MSB-first rule (MVP-SPEC.md line 96) is not \
                     being exercised",
                    case.name
                ),
            ));
        }
    }

    // 2. Unused slots are never derived: every grid node lying wholly at or
    //    past `n` must be refused, and the used set must be its complement.
    if tree.slot_count() <= u128::from(EXHAUSTIVE_SWEEP_SLOT_LIMIT) {
        for level in 0..=depth {
            for index in 0..(1u64 << level) {
                let address = address_of(level, index)?;
                let used = (index << (depth - level)) < n;
                if used != tree.seed_at(address).is_ok() {
                    return Err(check_err(
                        "unused-slot-refusal",
                        format!(
                            "case `{}`: node ({level},{index}) is {} but seed_at {} it",
                            case.name,
                            if used { "used" } else { "unused" },
                            if used { "refused" } else { "derived" },
                        ),
                    ));
                }
            }
        }
    }

    // 3. Every opening actually opens: the generated proof is run back
    //    through G13's verifier, which is the path a decoded bundle takes.
    let fine_root = rebuild_fine_root(s_root, content).ok_or_else(|| {
        check_err(
            "fine-root",
            format!("case `{}`: rebuild_fine_root returned None", case.name),
        )
    })?;
    for opening in &case.openings {
        let range = ByteRange::new(opening.start, opening.length);
        let proof: RangeProof = prove_range(s_root, content, range, n).map_err(|e| {
            check_err(
                "prove-range",
                format!("case `{}`, opening `{}`: {e}", case.name, opening.name),
            )
        })?;
        let start = usize::try_from(opening.start).unwrap_or(usize::MAX);
        let end = start.saturating_add(usize::try_from(opening.length).unwrap_or(usize::MAX));
        let revealed = content.get(start..end).ok_or_else(|| {
            check_err(
                "opening-range",
                format!(
                    "case `{}`, opening `{}`: range is not inside the content",
                    case.name, opening.name
                ),
            )
        })?;
        proof.verify(revealed, &fine_root).map_err(|e| {
            check_err(
                "opening-verifies",
                format!(
                    "case `{}`, opening `{}`: the committed proof does not verify: {e}",
                    case.name, opening.name
                ),
            )
        })?;
        // The seed-disclosure path is `cover_seeds` and nothing else; running
        // it here asserts the proof's cover is the one that path would ship.
        let cover = minimal_cover(range, n).map_err(|e| {
            check_err(
                "minimal-cover",
                format!("case `{}`, opening `{}`: {e}", case.name, opening.name),
            )
        })?;
        let disclosed: Vec<[u8; 32]> = cover_seeds(s_root, &cover)
            .iter()
            .map(|entry| *entry.payload().as_bytes())
            .collect();
        let in_proof: Vec<[u8; 32]> = proof
            .wire_cover()
            .iter()
            .filter_map(|node| <[u8; 32]>::try_from(node.bytes).ok())
            .collect();
        if disclosed != in_proof {
            return Err(check_err(
                "cover-seeds-agree",
                format!(
                    "case `{}`, opening `{}`: the proof's cover seeds are not the \
                     ones cover_seeds would disclose",
                    case.name, opening.name
                ),
            ));
        }
    }
    Ok(())
}

