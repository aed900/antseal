/// Execute a `fine-tree` vector (module docs).
///
/// `inputs`/`expect` arrive from the shared envelope, whose fields (schema,
/// version, NON-SECRET marker, format-version placement) are already checked
/// by the caller.
///
/// # Errors
///
/// Every [`VectorError`] class: a malformed payload, a recomputation that
/// disagrees with the committed document, or a behavioural assertion that
/// the committed values cannot express.
pub fn execute(
    inputs: serde_json::Value,
    expect: serde_json::Value,
    description: String,
) -> Result<VectorSummary, VectorError> {
    let parsed: Inputs =
        serde_json::from_value(inputs).map_err(|e| payload_err(format!("inputs: {e}")))?;

    // Fixture discipline: the document must derive from the documented seed.
    let w_bytes = decode_hex(KIND, "inputs.w", &parsed.w)?;
    let w_array: [u8; 32] = w_bytes
        .try_into()
        .map_err(|_| check_err("w-length", "inputs.w must be exactly 32 bytes".to_owned()))?;
    if w_array != TEST_MASTER_SECRET_W {
        return Err(check_err(
            "w-is-documented-test-seed",
            "inputs.w is not the documented fixed test seed 0x00..0x1f (testdata/README.md)"
                .to_owned(),
        ));
    }
    if parsed.s_root_label != S_ROOT_LABEL {
        return Err(check_err(
            "s-root-label",
            format!(
                "inputs.s_root_label is `{}`, the documented label is `{S_ROOT_LABEL}`",
                parsed.s_root_label
            ),
        ));
    }

    // 1. The whole `expect` object, recomputed and compared as one value.
    let recomputed = build_expect(&parsed)?;
    if recomputed != expect {
        return Err(check_err(
            "document",
            first_difference("expect", &recomputed, &expect),
        ));
    }

    // 2. The assertions a value comparison cannot express.
    let s_root = Seed32::from_bytes(alternate_test_secret(S_ROOT_LABEL.as_bytes()));
    for case in &parsed.cases {
        let content = decode_hex(KIND, "cases[].content", &case.content)?;
        check_case_behaviour(&s_root, case, &content)?;
    }

    // 3. Q5 bit-match: SHA-256 over the serialization of every recomputed
    //    artifact — not a verdict, the bytes themselves. Serializing the
    //    recomputed value (rather than hand-feeding fields) means a future
    //    field is covered the moment it is added.
    let serialized = serde_json::to_vec(&recomputed)
        .map_err(|e| check_err("digest-serialization", e.to_string()))?;
    let mut digest = Sha256::new();
    digest.update(RECOMPUTED_DIGEST_DOMAIN);
    digest.update(KIND.as_bytes());
    digest.update([0x00]);
    digest.update(super::vectors::prefix_len(serialized.len()));
    digest.update(&serialized);

    Ok(VectorSummary {
        kind: KIND,
        description,
        items: parsed.cases.len(),
        recomputed_digest: digest.finalize().into(),
    })
}

/// Recompute the entire `expect` object from `inputs`, through antseal-core's
/// public API (module docs).
///
/// Also the **regenerator**: `tests/fine_tree_vectors.rs` calls this and diffs
/// the result against the committed file, which is the G15-mandated
/// "regenerates and diffs, so drift fails CI" test.
///
/// # Errors
///
/// [`VectorError::Payload`] for a malformed case (bad hex, an opening whose
/// range the file's `n` cannot hold), and [`VectorError::Check`] for a case
/// the fine-tree API itself refuses.
fn build_expect(inputs: &Inputs) -> Result<serde_json::Value, VectorError> {
    let s_root = Seed32::from_bytes(alternate_test_secret(S_ROOT_LABEL.as_bytes()));
    let mut cases = Vec::with_capacity(inputs.cases.len());
    for case in &inputs.cases {
        let content = decode_hex(KIND, "cases[].content", &case.content)?;
        cases.push(build_case(&s_root, case, &content)?);
    }
    Ok(serde_json::json!({
        "s_root": hex(s_root.as_bytes()),
        "cases": cases,
    }))
}

/// Regenerate the whole document (envelope included) from a committed one's
/// `inputs`, so a regenerator can diff bytes-for-value against the file.
///
/// # Errors
///
/// As [`build_expect`], plus [`VectorError::Envelope`] when the supplied
/// document is not a `fine-tree` vector at all.
pub fn regenerate_expect(document: &serde_json::Value) -> Result<serde_json::Value, VectorError> {
    let kind = document.get("kind").and_then(serde_json::Value::as_str);
    if kind != Some(KIND) {
        return Err(VectorError::Envelope(format!(
            "not a `{KIND}` vector (kind is {kind:?})"
        )));
    }
    let inputs = document
        .get("inputs")
        .ok_or_else(|| VectorError::Envelope("document has no `inputs`".to_owned()))?;
    let parsed: Inputs =
        serde_json::from_value(inputs.clone()).map_err(|e| payload_err(format!("inputs: {e}")))?;
    build_expect(&parsed)
}

/// One case's `expect` entry.
fn build_case(
    s_root: &Seed32,
    case: &CaseInput,
    content: &[u8],
) -> Result<serde_json::Value, VectorError> {
    let n = u64::try_from(content.len()).unwrap_or(u64::MAX);
    let Some(depth) = depth_for_leaf_count(n) else {
        // n = 0: an empty file has no fine tree, so there is nothing to pin
        // but its absence (MVP-SPEC.md line 78).
        if !case.openings.is_empty() {
            return Err(check_err(
                "empty-file-has-no-openings",
                format!(
                    "case `{}` is empty (n = 0) but declares openings",
                    case.name
                ),
            ));
        }
        return Ok(serde_json::json!({
            "name": case.name,
            "n": 0,
            "depth": null,
            "slot_count": 0,
            "ggm_nodes": [],
            "salts": [],
            "merkle_nodes": [],
            "fine_root": null,
            "openings": [],
        }));
    };
    let tree = SaltTree::new(s_root, n).ok_or_else(|| {
        check_err(
            "salt-tree",
            format!("case `{}`: no salt tree for n = {n}", case.name),
        )
    })?;

    // Every grid node covering at least one real leaf, in (level, index)
    // order — "all GGM node seeds along used paths".
    let mut ggm_nodes = Vec::new();
    for (level, index) in used_grid_nodes(n, depth) {
        let address = address_of(level, index)?;
        let seed = tree.seed_at(address).map_err(|e| {
            check_err(
                "ggm-seed",
                format!("case `{}`: seed_at({level},{index}): {e}", case.name),
            )
        })?;
        ggm_nodes.push(serde_json::json!({
            "level": level,
            "index": index,
            "seed": hex(seed.as_bytes()),
        }));
    }

    // Every salt — the MSB-first pin.
    let mut salts = Vec::with_capacity(content.len());
    for index in 0..n {
        let salt = tree.salt(index).ok_or_else(|| {
            check_err(
                "salt",
                format!("case `{}`: no salt for leaf {index} of {n}", case.name),
            )
        })?;
        salts.push(serde_json::json!({
            "index": index,
            "salt": hex(salt.as_bytes()),
        }));
    }

    // Every RFC 6962 content-tree node, ordered by subtree width then first
    // leaf (level by level from the leaves up; the last entry is the root).
    let mut spans = Vec::new();
    collect_content_nodes(0, n, &mut spans);
    spans.sort_unstable_by_key(|&(first, end)| (end - first, first));
    let mut merkle_nodes = Vec::with_capacity(spans.len());
    for (first, end) in spans {
        let address = canonical_slot(first, end, n, depth).ok_or_else(|| {
            check_err(
                "canonical-slot",
                format!(
                    "case `{}`: [{first},{end}) is no content-tree node at n = {n}",
                    case.name
                ),
            )
        })?;
        merkle_nodes.push(serde_json::json!({
            "first": first,
            "end": end,
            "level": address.level(),
            "index": address.index(),
            "hash": hex(&subtree_hash(&tree, content, first, end)),
        }));
    }

    let fine_root = rebuild_fine_root(s_root, content).ok_or_else(|| {
        check_err(
            "fine-root",
            format!("case `{}`: rebuild_fine_root returned None", case.name),
        )
    })?;

    let mut openings = Vec::with_capacity(case.openings.len());
    for opening in &case.openings {
        openings.push(build_opening(s_root, case, content, n, opening)?);
    }

    Ok(serde_json::json!({
        "name": case.name,
        "n": n,
        "depth": depth,
        // `u64`: the grid of a `u64`-length file has at most 2^64 slots, which
        // JSON cannot hold — no committed case is anywhere near it, and
        // saturating keeps the executor total on a hostile `n`.
        "slot_count": u64::try_from(tree.slot_count()).unwrap_or(u64::MAX),
        "ggm_nodes": ggm_nodes,
        "salts": salts,
        "merkle_nodes": merkle_nodes,
        "fine_root": hex(fine_root.as_bytes()),
        "openings": openings,
    }))
}

/// One opening's `expect` entry: the full range proof (cover + boundary).
fn build_opening(
    s_root: &Seed32,
    case: &CaseInput,
    content: &[u8],
    leaf_count: u64,
    opening: &OpeningInput,
) -> Result<serde_json::Value, VectorError> {
    let named = |what: &str| format!("case `{}`, opening `{}`: {what}", case.name, opening.name);
    let range = ByteRange::new(opening.start, opening.length);
    let proof = prove_range(s_root, content, range, leaf_count)
        .map_err(|e| check_err("prove-range", named(&format!("prove_range failed: {e}"))))?;
    let cover = minimal_cover(range, leaf_count).map_err(|e| {
        check_err(
            "minimal-cover",
            named(&format!("minimal_cover failed: {e}")),
        )
    })?;

    let start = usize::try_from(opening.start)
        .map_err(|_| payload_err(named("start does not fit this platform's usize")))?;
    let end = start
        .checked_add(
            usize::try_from(opening.length)
                .map_err(|_| payload_err(named("length does not fit this platform's usize")))?,
        )
        .ok_or_else(|| payload_err(named("range end overflows")))?;
    let revealed = content
        .get(start..end)
        .ok_or_else(|| payload_err(named("range is not inside the content")))?;

    Ok(serde_json::json!({
        "name": opening.name,
        "start": opening.start,
        "length": opening.length,
        "revealed_bytes": hex(revealed),
        "releases_s_root": cover.releases_s_root(),
        "cover": proof
            .wire_cover()
            .iter()
            .map(|node| serde_json::json!({
                "level": node.level,
                "index": node.index,
                "seed": hex(node.bytes),
            }))
            .collect::<Vec<_>>(),
        "boundary": proof
            .wire_boundary()
            .iter()
            .map(|node| serde_json::json!({
                "level": node.level,
                "index": node.index,
                "hash": hex(node.bytes),
            }))
            .collect::<Vec<_>>(),
    }))
}

